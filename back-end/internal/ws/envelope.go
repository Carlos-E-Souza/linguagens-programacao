// Package ws defines the WebSocket wire contract: the envelope that
// wraps every frame and the payload types inside it.
//
// The names here are the public contract shared with the client, and they
// match the JSON tags, the REST fields and the database columns. A value
// never has to be renamed as it travels through the system.
package ws

import (
	"encoding/json"
	"fmt"

	"github.com/Carlos-E-Souza/linguagens-programacao/back-end/internal/models"
)

// Client to server message types.
const (
	TypeMessageSend      = "message.send"
	TypeMessageDelivered = "message.delivered"
	TypeMessageRead      = "message.read"
	TypeTyping           = "typing"
	TypeSync             = "sync"
)

// Server to client message types.
const (
	TypeMessageAck      = "message.ack"
	TypeMessageNew      = "message.new"
	TypeMessageStatus   = "message.status"
	TypePresence        = "presence"
	TypeConversationUpd = "conversation.updated"
	TypeSyncEnd         = "sync.end"
	TypeError           = "error"
	TypeServerShutdown  = "server.shutdown"
)

// Envelope wraps every frame. Data holds raw JSON so a frame can be
// decoded into the right payload type only once its Type is known.
type Envelope struct {
	Type string          `json:"type"`
	Data json.RawMessage `json:"data,omitempty"`
}

// NewEnvelope marshals a payload into an envelope ready to be sent.
func NewEnvelope(msgType string, payload any) (Envelope, error) {
	if payload == nil {
		return Envelope{Type: msgType}, nil
	}

	raw, err := json.Marshal(payload)
	if err != nil {
		return Envelope{}, fmt.Errorf("marshal %s payload: %w", msgType, err)
	}

	return Envelope{Type: msgType, Data: raw}, nil
}

// SendPayload is what the client sends to publish a message.
//
// ClientID is generated by the client and echoed back in the
// acknowledgement, which is how a client correlates the two and how the
// server deduplicates a resend after a reconnect.
type SendPayload struct {
	ClientID       string `json:"client_id"`
	ConversationID int64  `json:"conversation_id"`
	Body           string `json:"body"`
}

// AckPayload confirms that a message was accepted.
//
// A duplicate resend receives the same acknowledgement as the original,
// so the client cannot tell the difference and does not need to.
type AckPayload struct {
	ClientID       string `json:"client_id"`
	ID             int64  `json:"id"`
	ConversationID int64  `json:"conversation_id"`
	Sequence       int64  `json:"sequence"`
	CreatedAt      string `json:"created_at"`
}

// ConversationSequence identifies how far a client has progressed in one
// conversation.
type ConversationSequence struct {
	ConversationID int64 `json:"conversation_id"`
	LastSequence   int64 `json:"last_sequence"`
}

// SyncPayload asks for everything missed while offline.
type SyncPayload struct {
	Conversations []ConversationSequence `json:"conversations"`
}

// ReadReceiptPayload is sent for both delivered and read confirmations;
// the envelope type distinguishes them.
type ReadReceiptPayload struct {
	ConversationID int64 `json:"conversation_id"`
	UpToSequence   int64 `json:"up_to_sequence"`
}

// TypingPayload reports that a user started or stopped typing.
type TypingPayload struct {
	ConversationID int64 `json:"conversation_id"`
	Active         bool  `json:"active"`
}

// StatusPayload tells the sender how far the recipients have got.
type StatusPayload struct {
	ConversationID int64  `json:"conversation_id"`
	UserID         int64  `json:"user_id"`
	UpToSequence   int64  `json:"up_to_sequence"`
	Status         string `json:"status"`
}

// PresencePayload reports that a contact came online or went offline.
type PresencePayload struct {
	UserID int64 `json:"user_id"`
	Online bool  `json:"online"`
}

// TypingEvent is the server telling a member that somebody is typing.
type TypingEvent struct {
	ConversationID int64 `json:"conversation_id"`
	UserID         int64 `json:"user_id"`
	Active         bool  `json:"active"`
}

// ConversationUpdatedPayload announces a membership change.
type ConversationUpdatedPayload struct {
	Conversation models.Conversation `json:"conversation"`
}

// ErrorPayload reports a rejected request.
//
// ClientID is optional and present only when the failure can be tied to a
// specific message the client sent, so it can mark that message failed.
type ErrorPayload struct {
	Code     string `json:"code"`
	Message  string `json:"message"`
	ClientID string `json:"client_id,omitempty"`
}
